import type {
  TableDatabaseType,
  TableDefinition,
  TableFieldDefinition,
  TableForeignKeyDefinition,
  TableIndexDefinition,
} from './tableStructureTypes'
import { isMySQLCompatible } from './mysqlCompat'

export function quoteTableIdentifier(
  value: string,
  databaseType: TableDatabaseType,
): string {
  // MySQL 协议兼容类型（MySQL/TDSQL）标识符统一使用反引号引用
  if (isMySQLCompatible(databaseType)) {
    return `\`${value.replace(/`/g, '``')}\``
  }
  if (databaseType === 'SQL Server') {
    return `[${value.replace(/]/g, ']]')}]`
  }
  return `"${value.replace(/"/g, '""')}"`
}

export function tableReference(
  databaseType: TableDatabaseType,
  database: string,
  tableName: string,
): string {
  const quote = (value: string) => quoteTableIdentifier(value, databaseType)
  if (isMySQLCompatible(databaseType)) return `${quote(database)}.${quote(tableName)}`
  if (databaseType === 'SQL Server') {
    return `${quote(database)}.[dbo].${quote(tableName)}`
  }
  if (databaseType === 'PostgreSQL') return `"public".${quote(tableName)}`
  return quote(tableName)
}

export function quoteSqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`
}

export function buildColumnDefinition(
  databaseType: TableDatabaseType,
  field: TableFieldDefinition,
): string {
  const name = quoteTableIdentifier(field.name, databaseType)
  const defaultClause = field.defaultValue && !field.autoIncrement
    ? ` DEFAULT ${field.defaultValue}`
    : ''

  if (databaseType === 'SQLite' && field.autoIncrement) {
    return `${name} INTEGER PRIMARY KEY AUTOINCREMENT`
  }

  let sql = `${name} ${field.type}`
  if (databaseType === 'PostgreSQL' && field.autoIncrement) {
    sql += ' GENERATED BY DEFAULT AS IDENTITY'
  }
  if (databaseType === 'SQL Server' && field.autoIncrement) {
    sql += ' IDENTITY(1,1)'
  }
  sql += field.notNull || field.primary ? ' NOT NULL' : ' NULL'
  sql += defaultClause
  if (databaseType === 'MySQL' && field.autoIncrement) {
    sql += ' AUTO_INCREMENT'
  }
  if (databaseType === 'MySQL' && field.comment) {
    sql += ` COMMENT ${quoteSqlString(field.comment)}`
  }
  return sql
}

export function buildForeignKeyClause(
  databaseType: TableDatabaseType,
  foreignKey: TableForeignKeyDefinition,
): string {
  const quote = (value: string) => quoteTableIdentifier(value, databaseType)
  return [
    `CONSTRAINT ${quote(foreignKey.name)} FOREIGN KEY`,
    `(${foreignKey.fields.map(quote).join(', ')})`,
    `REFERENCES ${quote(foreignKey.referencedTable)}`,
    `(${foreignKey.referencedFields.map(quote).join(', ')})`,
  ].join(' ')
}

/**
 * 生成 TDSQL 建表语句的分表/广播后缀。
 * - shard 且已指定 shardKey → ` SHARDKEY=\`字段名\``
 * - broadcast → ` BROADCAST`
 * - noshard 或无选项 → 空串
 * 仅当 databaseType === 'TDSQL' 时生效，其他数据库类型直接返回空串。
 */
export function buildTDSQLTableSuffix(
  databaseType: TableDatabaseType,
  tdsqlOptions?: {
    tableType: 'shard' | 'noshard' | 'broadcast'
    shardKey?: string
  },
): string {
  if (databaseType !== 'TDSQL' || !tdsqlOptions) return ''
  if (tdsqlOptions.tableType === 'shard' && tdsqlOptions.shardKey) {
    return ` SHARDKEY=${quoteTableIdentifier(tdsqlOptions.shardKey, databaseType)}`
  }
  if (tdsqlOptions.tableType === 'broadcast') {
    return ' BROADCAST'
  }
  return ''
}

export function buildCreateTableStatements(
  databaseType: TableDatabaseType,
  database: string,
  definition: TableDefinition,
  overrideName?: string,
  tdsqlOptions?: {
    tableType: 'shard' | 'noshard' | 'broadcast'
    shardKey?: string
  },
): string[] {
  const tableName = overrideName || definition.name
  const quote = (value: string) => quoteTableIdentifier(value, databaseType)
  const clauses = definition.fields.map(
    field => buildColumnDefinition(databaseType, field),
  )
  const primaryFields = definition.fields.filter(field => field.primary)
  const hasInlinePrimary = (
    databaseType === 'SQLite'
    && primaryFields.length === 1
    && primaryFields[0].autoIncrement
  )
  if (primaryFields.length > 0 && !hasInlinePrimary) {
    clauses.push(
      `PRIMARY KEY (${primaryFields.map(field => quote(field.name)).join(', ')})`,
    )
  }
  clauses.push(...definition.foreignKeys.map(
    foreignKey => buildForeignKeyClause(databaseType, foreignKey),
  ))

  // TDSQL 建表需在 CREATE TABLE 末尾追加分表/广播子句
  const tdsqlSuffix = buildTDSQLTableSuffix(databaseType, tdsqlOptions)

  const statements = [
    `CREATE TABLE ${tableReference(databaseType, database, tableName)} (\n  ${clauses.join(',\n  ')}\n)${tdsqlSuffix}`,
  ]
  statements.push(...definition.indexes.map(index => buildCreateIndexStatement(
    databaseType,
    database,
    tableName,
    index,
  )))
  statements.push(...buildCommentStatements(
    databaseType,
    database,
    tableName,
    definition.fields,
  ))
  return statements
}

export function buildCreateIndexStatement(
  databaseType: TableDatabaseType,
  database: string,
  tableName: string,
  index: TableIndexDefinition,
): string {
  const quote = (value: string) => quoteTableIdentifier(value, databaseType)
  const indexName = databaseType === 'PostgreSQL'
    ? `"public".${quote(index.name)}`
    : quote(index.name)
  return `CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX ${indexName} ON ${tableReference(databaseType, database, tableName)} (${index.fields.map(quote).join(', ')})`
}

export function buildCommentStatements(
  databaseType: TableDatabaseType,
  database: string,
  tableName: string,
  fields: TableFieldDefinition[],
): string[] {
  if (databaseType !== 'PostgreSQL') return []
  const quote = (value: string) => quoteTableIdentifier(value, databaseType)
  const table = tableReference(databaseType, database, tableName)
  return fields.map(field => (
    `COMMENT ON COLUMN ${table}.${quote(field.name)} IS ${field.comment ? quoteSqlString(field.comment) : 'NULL'}`
  ))
}

export function normalizedSqlValue(value: string): string {
  return value.trim().replace(/\s+/g, ' ').toLocaleLowerCase()
}

function sameOrderedValues(left: string[], right: string[]): boolean {
  return (
    left.length === right.length
    && left.every((value, index) => value === right[index])
  )
}

function sameMappedFields(
  original: TableDefinition,
  definition: TableDefinition,
): boolean {
  return (
    original.fields.length === definition.fields.length
    && definition.fields.every(field => {
      const source = original.fields.find(
        item => item.name === field.originalName,
      )
      return Boolean(
        source
        && source.name === field.name
        && normalizedSqlValue(source.type) === normalizedSqlValue(field.type)
        && (source.notNull || source.primary)
          === (field.notNull || field.primary)
        && source.primary === field.primary
        && source.autoIncrement === field.autoIncrement
        && normalizedSqlValue(source.defaultValue)
          === normalizedSqlValue(field.defaultValue)
        && source.comment === field.comment,
      )
    })
  )
}

function sameMappedIndexes(
  original: TableDefinition,
  definition: TableDefinition,
): boolean {
  return (
    original.indexes.length === definition.indexes.length
    && definition.indexes.every(index => {
      const source = original.indexes.find(
        item => item.name === index.originalName,
      )
      return Boolean(
        source
        && source.name === index.name
        && source.unique === index.unique
        && sameOrderedValues(source.fields, index.fields),
      )
    })
  )
}

function sameMappedForeignKeys(
  original: TableDefinition,
  definition: TableDefinition,
): boolean {
  return (
    original.foreignKeys.length === definition.foreignKeys.length
    && definition.foreignKeys.every(foreignKey => {
      const source = original.foreignKeys.find(
        item => item.name === foreignKey.originalName,
      )
      return Boolean(
        source
        && source.name === foreignKey.name
        && source.referencedTable === foreignKey.referencedTable
        && sameOrderedValues(source.fields, foreignKey.fields)
        && sameOrderedValues(
          source.referencedFields,
          foreignKey.referencedFields,
        ),
      )
    })
  )
}

export function sameTableDefinition(
  original: TableDefinition,
  definition: TableDefinition,
): boolean {
  return (
    original.name === definition.name
    && sameMappedFields(original, definition)
    && sameMappedIndexes(original, definition)
    && sameMappedForeignKeys(original, definition)
  )
}
