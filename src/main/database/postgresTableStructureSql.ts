import {
  buildColumnDefinition,
  buildCommentStatements,
  buildCreateIndexStatement,
  buildForeignKeyClause,
  quoteTableIdentifier,
  tableReference,
} from './tableStructureSqlCommon'
import type {
  TableDefinition,
  TableFieldDefinition,
  TableStructurePlan,
} from './tableStructureTypes'

function primaryConstraintName(definition: TableDefinition): string {
  return definition.primaryKeyName || `${definition.name}_pkey`
}

function alterExistingField(
  table: string,
  field: TableFieldDefinition,
  originalField: TableFieldDefinition,
): string[] {
  const quote = (value: string) => quoteTableIdentifier(value, 'PostgreSQL')
  const name = quote(field.name)
  const statements: string[] = []
  if (field.originalName && field.originalName !== field.name) {
    statements.push(
      `ALTER TABLE ${table} RENAME COLUMN ${quote(field.originalName)} TO ${name}`,
    )
  }
  if (field.type !== originalField.type) {
    statements.push(
      `ALTER TABLE ${table} ALTER COLUMN ${name} TYPE ${field.type} USING ${name}::${field.type}`,
    )
  }
  if (field.autoIncrement !== originalField.autoIncrement) {
    statements.push(
      field.autoIncrement
        ? `ALTER TABLE ${table} ALTER COLUMN ${name} ADD GENERATED BY DEFAULT AS IDENTITY`
        : `ALTER TABLE ${table} ALTER COLUMN ${name} DROP IDENTITY IF EXISTS`,
    )
  }
  statements.push(
    field.notNull || field.primary
      ? `ALTER TABLE ${table} ALTER COLUMN ${name} SET NOT NULL`
      : `ALTER TABLE ${table} ALTER COLUMN ${name} DROP NOT NULL`,
  )
  if (!field.autoIncrement) {
    statements.push(
      field.defaultValue
        ? `ALTER TABLE ${table} ALTER COLUMN ${name} SET DEFAULT ${field.defaultValue}`
        : `ALTER TABLE ${table} ALTER COLUMN ${name} DROP DEFAULT`,
    )
  }
  return statements
}

export function buildPostgresAlterPlan(
  database: string,
  original: TableDefinition,
  definition: TableDefinition,
): TableStructurePlan {
  const quote = (value: string) => quoteTableIdentifier(value, 'PostgreSQL')
  let table = tableReference('PostgreSQL', database, original.name)
  const statements: string[] = []

  original.foreignKeys.forEach(foreignKey => {
    statements.push(
      `ALTER TABLE ${table} DROP CONSTRAINT IF EXISTS ${quote(foreignKey.name)}`,
    )
  })
  original.indexes.forEach(index => {
    statements.push(`DROP INDEX IF EXISTS "public".${quote(index.name)}`)
  })
  if (original.fields.some(field => field.primary)) {
    statements.push(
      `ALTER TABLE ${table} DROP CONSTRAINT IF EXISTS ${quote(primaryConstraintName(original))}`,
    )
  }

  const retainedNames = new Set(
    definition.fields
      .map(field => field.originalName)
      .filter((name): name is string => Boolean(name)),
  )
  original.fields
    .filter(field => !retainedNames.has(field.name))
    .forEach(field => {
      statements.push(`ALTER TABLE ${table} DROP COLUMN ${quote(field.name)}`)
    })

  definition.fields.forEach(field => {
    if (!field.originalName) {
      statements.push(
        `ALTER TABLE ${table} ADD COLUMN ${buildColumnDefinition('PostgreSQL', field)}`,
      )
      return
    }
    const originalField = original.fields.find(
      item => item.name === field.originalName,
    )
    if (!originalField) {
      throw new Error(`原字段不存在: ${field.originalName}`)
    }
    statements.push(...alterExistingField(table, field, originalField))
  })

  if (definition.name !== original.name) {
    statements.push(`ALTER TABLE ${table} RENAME TO ${quote(definition.name)}`)
    table = tableReference('PostgreSQL', database, definition.name)
  }

  const primaryFields = definition.fields.filter(field => field.primary)
  if (primaryFields.length > 0) {
    statements.push(
      `ALTER TABLE ${table} ADD CONSTRAINT ${quote(primaryConstraintName(definition))} PRIMARY KEY (${primaryFields.map(field => quote(field.name)).join(', ')})`,
    )
  }
  definition.foreignKeys.forEach(foreignKey => {
    statements.push(
      `ALTER TABLE ${table} ADD ${buildForeignKeyClause('PostgreSQL', foreignKey)}`,
    )
  })
  definition.indexes.forEach(index => {
    statements.push(buildCreateIndexStatement(
      'PostgreSQL',
      database,
      definition.name,
      index,
    ))
  })
  statements.push(...buildCommentStatements(
    'PostgreSQL',
    database,
    definition.name,
    definition.fields,
  ))

  return { mode: 'alter', statements, warnings: [] }
}
